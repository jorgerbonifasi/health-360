-- Health 360 — AI coach plan history + post-run review.
--
-- Until now the coach's recommendation was returned straight to the browser and held in React
-- state, so it vanished on reload and there was nothing to compare a run against. This table
-- keeps one row per day: `run-plan` writes it (upsert on `date`, so regenerating replaces that
-- day's plan), and `run-review` later fills the review_* columns by comparing the plan with what
-- was actually done.
--
-- NOTE: this project has "Automatically expose new tables" OFF, so the grants at the bottom are
-- mandatory — without them the Edge Functions get "permission denied".

create table if not exists public.run_plans (
  id          bigint generated always as identity primary key,
  date        date        not null unique,  -- the day the plan is FOR (UTC)

  -- The prescription. plan_text is the prose rendered on the card; the structured columns are
  -- what the review compares against and are null on a rest day.
  plan_text               text    not null,
  workout_type            text    not null,  -- easy | recovery | tempo | intervals | long | rest
  target_distance_km      numeric,
  target_pace_min_km_low  numeric,           -- decimal minutes per km (5.5 = 5:30/km)
  target_pace_min_km_high numeric,
  target_hr_low           integer,
  target_hr_high          integer,
  why                     text,
  reminder                text,

  feel         text,                         -- the athlete's own note at plan time
  model        text        not null,
  generated_at timestamptz not null default now(),

  -- Filled in by run-review. actual_* are computed from `activities`, never generated by the
  -- model — only review_text and adherence are the model's judgement.
  reviewed_at         timestamptz,
  review_text         text,
  adherence           text,
  actual_distance_km  numeric,
  actual_pace_min_km  numeric,
  actual_avg_hr       numeric,
  reviewed_strava_ids bigint[],
  review_model        text,

  created_at timestamptz not null default now()
);

create index if not exists run_plans_date_idx on public.run_plans (date desc);

-- followed        — did broadly what was asked
-- harder/easier   — ran, but meaningfully above/below the prescription
-- skipped         — a run was prescribed and nothing happened
-- cross_trained   — trained, but not the prescribed run
-- rest_as_planned — rest was prescribed and taken
-- extra           — rest was prescribed and they trained anyway
alter table public.run_plans drop constraint if exists run_plans_adherence_check;
alter table public.run_plans add constraint run_plans_adherence_check check (
  adherence is null or adherence in
    ('followed', 'harder', 'easier', 'skipped', 'cross_trained', 'rest_as_planned', 'extra')
);

alter table public.run_plans enable row level security;

drop policy if exists "read run_plans" on public.run_plans;
create policy "read run_plans" on public.run_plans for select to anon, authenticated using (true);

-- Explicit grants (see note at the top).
grant select on public.run_plans to anon, authenticated;
grant select, insert, update, delete on public.run_plans to service_role;
